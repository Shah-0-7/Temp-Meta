/**
 * @module providers/tryon-generator/RemoteTryOnGenerator
 *
 * Tier B through the app's own server (`POST /api/generate`), which relays to a free
 * hosted model. The browser never talks to the model host and never holds a key.
 *
 * The person's photo leaves the device, so `requestConsent` must be answered first.
 * Every vendor/host detail stays on the server; this class only knows the app's own
 * small contract: multipart `person`, `garment`, `garmentType` in, an image out, or
 * `{ error: { code, message } }`.
 */

import type {
  ProviderCapability,
  TryOnGenerator,
  TryOnRequest,
  TryOnResult,
} from '../types.js';
import { ContentPolicyError, NotConfiguredError, RateLimitError } from '../types.js';
import { ConsentDeclinedError } from './errors.js';
import { prepareGarmentImage, preparePersonImage } from './imagePrep.js';

export class RemoteTryOnError extends Error {
  constructor(
    public readonly code: string,
    message: string,
  ) {
    super(message);
    this.name = 'RemoteTryOnError';
  }
}

export interface RemoteTryOnOptions {
  /** Absolute or relative URL of the server's generate route. */
  endpoint: string;
  /** Shown to the person, e.g. "Leffa (free Hugging Face Space)". */
  label: string;
  /** Resolves true when the person agrees to send the images. */
  requestConsent: () => Promise<boolean>;
  fetchFn?: typeof fetch;
  preparePerson?: (blob: Blob) => Promise<Blob>;
  prepareGarment?: (blob: Blob) => Promise<Blob>;
  /** Client-side wait limit. Free GPUs queue, so this is generous. Default 170 s. */
  timeoutMs?: number;
}

async function readError(res: Response): Promise<{ code: string; message: string }> {
  try {
    const body = (await res.json()) as { error?: { code?: string; message?: string } };
    return { code: body?.error?.code ?? 'unknown', message: body?.error?.message ?? '' };
  } catch {
    return { code: 'unknown', message: '' };
  }
}

export class RemoteTryOnGenerator implements TryOnGenerator {
  readonly name = 'remote-tryon';
  readonly capabilities: readonly ProviderCapability[] = ['tryon-generator'];
  readonly sendsDataOffDevice = true;

  constructor(private readonly _o: RemoteTryOnOptions) {}

  async initialize(): Promise<void> {
    /* Stateless: each render is one request. */
  }

  async dispose(): Promise<void> {
    /* Nothing to release. */
  }

  supportsRefinement(): boolean {
    return false;
  }

  async refine(): Promise<TryOnResult> {
    throw new NotConfiguredError(this.name, 'This AI render cannot be refined. Render again instead.');
  }

  async generate(request: TryOnRequest): Promise<TryOnResult> {
    const garment = request.garmentImages[0];
    if (!garment) throw new RemoteTryOnError('bad_request', 'No garment image was provided.');

    if (!(await this._o.requestConsent())) throw new ConsentDeclinedError();

    const prepPerson = this._o.preparePerson ?? ((b: Blob) => preparePersonImage(b));
    const prepGarment = this._o.prepareGarment ?? ((b: Blob) => prepareGarmentImage(b));

    const form = new FormData();
    form.append('person', await prepPerson(request.personFrame), 'person.jpg');
    form.append('garment', await prepGarment(garment), 'garment.png');
    form.append('garmentType', request.garmentType);

    const doFetch = this._o.fetchFn ?? fetch;
    let res: Response;
    try {
      res = await doFetch(this._o.endpoint, {
        method: 'POST',
        body: form,
        signal: AbortSignal.timeout(this._o.timeoutMs ?? 170_000),
      });
    } catch (err) {
      const timedOut = (err as Error)?.name === 'TimeoutError' || (err as Error)?.name === 'AbortError';
      throw new RemoteTryOnError(
        timedOut ? 'timeout' : 'network',
        timedOut ? 'The AI service took too long.' : 'Could not reach the app server.',
      );
    }

    if (!res.ok) {
      const { code, message } = await readError(res);
      if (res.status === 429) {
        const retry = Number(res.headers.get('Retry-After'));
        throw new RateLimitError(this._o.label, Number.isFinite(retry) && retry > 0 ? retry * 1000 : undefined);
      }
      if (code === 'content_policy') throw new ContentPolicyError(this._o.label);
      if (res.status === 404 || code === 'feature_disabled') {
        throw new NotConfiguredError(this.name, 'The server has no AI model configured.');
      }
      throw new RemoteTryOnError(code, message || `The AI service answered ${res.status}.`);
    }

    const image = await res.blob();
    if (!/^image\//i.test(image.type) || image.size === 0) {
      throw new RemoteTryOnError('bad_response', 'The AI service returned something that is not an image.');
    }
    return {
      image,
      metadata: {
        provider: this._o.label,
        note: 'AI-generated by a free online model. Details such as the print or fit can differ from the real garment.',
      },
    };
  }
}
